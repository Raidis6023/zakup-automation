const MIN_DELAY = 30_000;
const RANDOM_EXTRA_DELAY = 15_000;
const FADE_DURATION = 350;

export default function HomePandaAssistant() {
  const [index, setIndex] = useState(0);
  const [changing, setChanging] = useState(false);

  useEffect(() => {
    let swapTimer: ReturnType<typeof setTimeout> | undefined;
    const changeTimer = window.setTimeout(() => {
      setChanging(true);
      swapTimer = window.setTimeout(() => {
        setIndex(previous => {
          // Выбираем случайную фразу, исключая немедленный повтор.
          const offset = 1 + Math.floor(Math.random() * (PHRASES.length - 1));
          return (previous + offset) % PHRASES.length;
        });
        setChanging(false);
      }, FADE_DURATION);
    }, MIN_DELAY + Math.floor(Math.random() * RANDOM_EXTRA_DELAY));

    return () => {
      window.clearTimeout(changeTimer);
      if (swapTimer !== undefined) window.clearTimeout(swapTimer);
    };
  }, [index]);

  const phrase = PHRASES[index];

  return (
    <aside className={styles.assistant} aria-label="Панда WorkSpace">
      <div className={styles.bubble}>
        <p className={changing ? styles.hidden : styles.visible}>
          <strong>{phrase.intro}</strong>{" "}{phrase.message}
        </p>
      </div>
      <Image
        src="/panda/home-panda-stool.avif"
        alt="Красная панда в чёрном костюме сидит на стуле, скрестив ноги, и приветствует коллег"
        width={525}
        height={700}
        className={styles.panda}
        priority
        unoptimized
        draggable={false}
      />
    </aside>
  );
}
