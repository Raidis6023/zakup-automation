"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const read = file => fs.readFileSync(path.join(__dirname, "..", file), "utf8");
const theme = read("app/workspace-unified-champagne.css");
const unit = read("app/unit-economics/UnitEconomicsClient.tsx");
const pilot = read("app/unit-economics/UnitEconomicsPilotClient.tsx");
const tasks = read("app/tasks/TasksBoard.tsx");
assert.match(theme, /@supports \(appearance: base-select\)/);
assert.match(theme, /select:not\(\[multiple\]\):not\(\[size\]\)/);
assert.match(theme, /::picker\(select\)/);
assert.match(theme, /option:checked/);
assert.match(theme, /display:\s*flex;\s*align-items:\s*center;\s*justify-content:\s*space-between;/, "All single-choice selectors keep their labels vertically centered");
assert.match(theme, /option\s*\{\s*display:\s*flex;\s*align-items:\s*center;/, "Picker items are vertically centered");
assert.match(theme, /option::checkmark\s*\{[^}]*display:\s*none\s*!important;/, "Native option checkmarks must be hidden globally");
assert.match(theme, /option::checkmark\s*\{[^}]*content:\s*none\s*!important;/, "No generated checkmark content");
assert.match(theme, /background-position:\s*right 11px center\s*!important;/, "Custom select arrow stays pinned to the right edge");
assert.match(theme, /padding-inline-end:\s*32px\s*!important;/, "Reserve space so text never overlaps the arrow");
assert.match(theme, /background-size:\s*12px 8px\s*!important;/, "Arrow has a consistent size");
assert.match(theme, /::picker-icon\s*\{\s*display:\s*none\s*!important;/, "Native arrows must not drift inward");
assert.match(theme, /html\[data-theme="dark"\][^\n]*select:not/, "Dark theme uses its own arrow color");
assert.match(theme, /option:hover/);
assert.equal((theme.match(/background-image:[^\n]+!important/g)||[]).length,4,
  "Two search magnifiers and two select arrows, one per theme each");
assert.match(pilot, /className="workspace-search-field" aria-label="Поиск пилотных товаров"/);
assert.doesNotMatch(unit, /unit-model-caption/);
assert.match(tasks, /className="tasks-department-picker"/);
assert.match(tasks, /onChange=\{e => setTarget\(e\.target\.value\)\}/);
console.log("PASS branded native dropdown picker, pilot search icon and hidden Google Sheets sheet captions");
